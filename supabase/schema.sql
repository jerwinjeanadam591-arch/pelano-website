create table if not exists public.quote_requests (
    id uuid primary key default gen_random_uuid(),
    reference_code text not null unique,
    channel text not null check (channel in ('email', 'whatsapp')),
    status text not null default 'new' check (status in ('new', 'reviewing', 'quoted', 'approved', 'fulfilled', 'closed')),
    name text not null,
    company text,
    email text not null,
    phone text,
    quantity text,
    delivery_location text,
    required_timeline text,
    specifications text,
    products jsonb not null default '[]'::jsonb,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

alter table public.quote_requests enable row level security;

create policy "Allow anonymous quote creation"
    on public.quote_requests
    for insert
    to anon
    with check (
        length(trim(name)) between 1 and 100
        and length(trim(email)) between 3 and 160
        and jsonb_typeof(products) = 'array'
    );

create index if not exists quote_requests_status_idx on public.quote_requests (status);
create index if not exists quote_requests_created_at_idx on public.quote_requests (created_at desc);

create table if not exists public.profiles (
    id uuid primary key references auth.users(id) on delete cascade,
    full_name text,
    role text not null default 'sales' check (role in ('admin', 'sales')),
    created_at timestamptz not null default now()
);

alter table public.profiles enable row level security;

create or replace function public.is_staff()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
    select exists (
        select 1
        from public.profiles
        where id = auth.uid()
          and role in ('admin', 'sales')
    );
$$;

create policy "Staff can view profiles"
    on public.profiles
    for select
    to authenticated
    using (id = auth.uid() or public.is_staff());

create policy "Staff can view quotes"
    on public.quote_requests
    for select
    to authenticated
    using (public.is_staff());

create policy "Staff can update quotes"
    on public.quote_requests
    for update
    to authenticated
    using (public.is_staff())
    with check (public.is_staff());

