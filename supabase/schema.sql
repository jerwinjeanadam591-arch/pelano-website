create table if not exists public.newsletter_request_limits (
    request_key_hash text primary key check (request_key_hash ~ '^[a-f0-9]{64}$'),
    window_started_at timestamptz not null,
    request_count integer not null check (request_count > 0),
    updated_at timestamptz not null
);

alter table public.newsletter_request_limits enable row level security;
revoke all on public.newsletter_request_limits from anon, authenticated;

create or replace function public.consume_newsletter_signup_limit(p_request_key_hash text)
returns boolean
language plpgsql
security definer
set search_path = public
as $$
declare
    current_count integer;
    current_time timestamptz := now();
begin
    if auth.role() <> 'service_role'
       or p_request_key_hash !~ '^[a-f0-9]{64}$' then
        raise exception 'Unauthorized newsletter rate-limit request.';
    end if;

    delete from public.newsletter_request_limits
    where updated_at < current_time - interval '1 day';

    insert into public.newsletter_request_limits (request_key_hash, window_started_at, request_count, updated_at)
    values (p_request_key_hash, current_time, 1, current_time)
    on conflict (request_key_hash) do update
    set window_started_at = case
            when public.newsletter_request_limits.window_started_at < current_time - interval '15 minutes'
            then current_time
            else public.newsletter_request_limits.window_started_at
        end,
        request_count = case
            when public.newsletter_request_limits.window_started_at < current_time - interval '15 minutes'
            then 1
            else public.newsletter_request_limits.request_count + 1
        end,
        updated_at = current_time
    returning request_count into current_count;

    return current_count <= 4;
end;
$$;

revoke all on function public.consume_newsletter_signup_limit(text) from public, anon, authenticated;
grant execute on function public.consume_newsletter_signup_limit(text) to service_role;

